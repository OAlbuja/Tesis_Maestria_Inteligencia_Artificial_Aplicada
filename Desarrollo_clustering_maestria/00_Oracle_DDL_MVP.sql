-- 4.6 Vista de Validación Directa Capa 2
CREATE OR REPLACE VIEW VW_VALIDACION_EXTERNA_CAPA2 AS
SELECT * FROM ML_VALIDACION_CAPA2;

-- 4.7 Vista Consulta 360 RUC (Uniendo Golden, SRI, SCVS, Clusters y Prioridad)
CREATE OR REPLACE VIEW VW_CONSULTA_RUC_SRI AS
WITH RANKING_ACTUAL AS (
    SELECT EXPEDIENTE, ANIO, INGRESOS, EMPLEADOS,
           ROW_NUMBER() OVER (PARTITION BY EXPEDIENTE ORDER BY ANIO DESC) as rn
    FROM SCVS_RANKING_RESUMEN
),
LATEST_CLUSTER_CAPA2 AS (
    SELECT RUC, SEGMENTO,
           ROW_NUMBER() OVER (PARTITION BY RUC ORDER BY ANIO DESC) as rn
    FROM ML_CLUSTERS_CAPA2
)
SELECT 
    g.RUC,
    g.RAZON_SOCIAL AS RAZON_SOCIAL_GOLDEN,
    sri.ESTADO_CONTRIBUYENTE,
    sri.TIPO_CONTRIBUYENTE,
    sri.CIIU_PRINCIPAL,
    sri.PROVINCIA_PRINCIPAL,
    c1.SEGMENTO AS SEGMENTO_CAPA1,
    c2.SEGMENTO AS SEGMENTO_CAPA2,
    l1.ES_CLIENTE_FPA,
    scvs.EXPEDIENTE,
    rnk.INGRESOS,
    rnk.EMPLEADOS,
    rnk.ANIO AS ANIO_FINANCIERO,
    -- Lógica de Priorización (Clustering a Acción Comercial)
    CASE 
        WHEN l1.ES_CLIENTE_FPA = 1 THEN 'Cliente Actual'
        WHEN c2.SEGMENTO = 'Grandes consolidadas' OR c1.SEGMENTO IN ('Industriales', 'Comercio maduro') THEN 'Foco Alto'
        WHEN c2.SEGMENTO = 'Medianas/recientes' THEN 'Foco Medio'
        WHEN c1.SEGMENTO IS NOT NULL THEN 'Foco Bajo'
        ELSE 'Sin Clasificar'
    END AS NIVEL_PRIORIDAD
FROM ML_EMPRESAS_MASTER g
LEFT JOIN SRI_RUC_EMPRESAS_RESUMEN sri ON g.RUC = sri.RUC
LEFT JOIN ML_CLUSTERS_CAPA1 c1 ON g.RUC = c1.RUC
LEFT JOIN ML_LABELS_CAPA1 l1 ON g.RUC = l1.RUC
LEFT JOIN LATEST_CLUSTER_CAPA2 c2 ON g.RUC = c2.RUC AND c2.rn = 1
LEFT JOIN SCVS_DIRECTORIO scvs ON g.RUC = scvs.RUC
LEFT JOIN RANKING_ACTUAL rnk ON scvs.EXPEDIENTE = rnk.EXPEDIENTE AND rnk.rn = 1;
