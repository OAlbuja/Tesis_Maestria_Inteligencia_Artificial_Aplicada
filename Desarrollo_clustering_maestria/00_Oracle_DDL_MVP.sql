-- 4. VISTAS PARA DASHBOARDS APEX
-- ====================================================================

-- 4.1 Vista Principal Capa 1
CREATE OR REPLACE VIEW VW_EMPRESAS_CLUSTER_CAPA1 AS
SELECT 
    g.RUC,
    g.RAZON_SOCIAL,
    g.PAIS_EMPRESA,
    c.CLUSTER_ID,
    c.SEGMENTO,
    l.ES_CLIENTE_FPA,
    f.SECTOR_CIIU_MACRO,
    f.REGION,
    f.ANTIGUEDAD_ANOS,
    f.TIPO_SOCIEDAD
FROM ML_EMPRESAS_MASTER g
JOIN ML_CLUSTERS_CAPA1 c ON g.RUC = c.RUC
JOIN ML_FEATURES_CAPA1 f ON g.RUC = f.RUC
JOIN ML_LABELS_CAPA1 l ON g.RUC = l.RUC;

-- 4.2 Vista Principal Capa 2
CREATE OR REPLACE VIEW VW_EMPRESAS_CLUSTER_CAPA2 AS
SELECT 
    g.RUC,
    g.RAZON_SOCIAL,
    c.CLUSTER_ID,
    c.SEGMENTO,
    l.ES_CLIENTE_FPA,
    f.ANIO,
    f.SECTOR_CIIU_MACRO,
    f.REGION,
    f.LOG_EMPLEADOS,
    f.LOG_INGRESOS,
    f.LOG_ACTIVOS
FROM ML_EMPRESAS_MASTER g
JOIN ML_CLUSTERS_CAPA2 c ON g.RUC = c.RUC AND c.ANIO = (SELECT MAX(ANIO) FROM ML_CLUSTERS_CAPA2 WHERE RUC = g.RUC)
JOIN ML_FEATURES_CAPA2 f ON c.RUC = f.RUC AND c.ANIO = f.ANIO
JOIN ML_LABELS_CAPA2 l ON c.RUC = l.RUC AND c.ANIO = l.ANIO;

-- 4.3 Vista Resumen Capa 1
CREATE OR REPLACE VIEW VW_RESUMEN_CLUSTER_CAPA1 AS
SELECT 
    CLUSTER_ID,
    SEGMENTO,
    COUNT(RUC) AS TOTAL_EMPRESAS,
    SUM(ES_CLIENTE_FPA) AS TOTAL_CLIENTES_FPA,
    ROUND(SUM(ES_CLIENTE_FPA) / COUNT(RUC) * 100, 2) AS TASA_PENETRACION_PCT
FROM VW_EMPRESAS_CLUSTER_CAPA1
GROUP BY CLUSTER_ID, SEGMENTO;

-- 4.4 Vista Resumen Capa 2
CREATE OR REPLACE VIEW VW_RESUMEN_CLUSTER_CAPA2 AS
SELECT 
    CLUSTER_ID,
    SEGMENTO,
    COUNT(RUC) AS TOTAL_EMPRESAS,
    ROUND(AVG(LOG_INGRESOS), 2) AS PROMEDIO_LOG_INGRESOS,
    ROUND(AVG(LOG_EMPLEADOS), 2) AS PROMEDIO_LOG_EMPLEADOS,
    SUM(ES_CLIENTE_FPA) AS TOTAL_CLIENTES_FPA
FROM VW_EMPRESAS_CLUSTER_CAPA2
GROUP BY CLUSTER_ID, SEGMENTO;

-- 4.5 Vista de Validación Directa Capa 1
CREATE OR REPLACE VIEW VW_VALIDACION_EXTERNA_CAPA1 AS
